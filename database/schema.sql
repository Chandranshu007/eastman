    -- Table: public.orders

-- DROP TABLE IF EXISTS public.orders;

CREATE TABLE IF NOT EXISTS public.orders
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    subtotal numeric(12,2) NOT NULL,
    discount numeric(12,2) NOT NULL DEFAULT 0,
    total numeric(12,2) NOT NULL,
    coupon_id bigint,
    coupon_code character varying(40) COLLATE pg_catalog."default",
    status character varying(20) COLLATE pg_catalog."default" NOT NULL DEFAULT 'placed'::character varying,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT orders_coupon_id_fkey FOREIGN KEY (coupon_id)
        REFERENCES public.coupons (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE SET NULL,
    CONSTRAINT orders_check CHECK (discount >= 0::numeric AND discount <= subtotal),
    CONSTRAINT orders_check1 CHECK (total = (subtotal - discount)),
    CONSTRAINT orders_status_check CHECK (status::text = ANY (ARRAY['placed'::character varying, 'cancelled'::character varying]::text[])),
    CONSTRAINT orders_subtotal_check CHECK (subtotal >= 0::numeric),
    CONSTRAINT orders_total_check CHECK (total >= 0::numeric)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.orders
    OWNER to postgres;
-- Index: idx_orders_created_at

-- DROP INDEX IF EXISTS public.idx_orders_created_at;

CREATE INDEX IF NOT EXISTS idx_orders_created_at
    ON public.orders USING btree
    (created_at DESC NULLS FIRST)
;



